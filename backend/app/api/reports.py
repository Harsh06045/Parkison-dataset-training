"""
NeuroFusionAI Automated Patient PDF Report API Router.
Implements:
- POST /api/reports/generate/{patient_id}
- GET /api/reports/{report_id}
- GET /api/reports/{report_id}/download
- GET /api/reports/patient/{patient_id}
- GET /api/reports/doctor/{doctor_id}
- DELETE /api/reports/{report_id}

Enforces strict Role-Based Access Control (RBAC) and doctor-patient data isolation.
"""

from typing import Dict, Any, Optional, List
from fastapi import APIRouter, Depends, Request, Response, Body, status, HTTPException
from fastapi.responses import JSONResponse, FileResponse

from app.schemas.report import GenerateReportRequest, ReportResponse, ReportDetailResponse
from app.services.patient_report_service import patient_report_service
from app.utils.security import get_current_user, require_roles

router = APIRouter()


# -----------------------------------------------------------------------------
# 1. GENERATE PATIENT REPORT
# -----------------------------------------------------------------------------
@router.post(
    "/generate/{patient_id}",
    response_model=ReportDetailResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Generate Patient Medical Report"
)
def generate_patient_report_endpoint(
    patient_id: str,
    payload: Optional[GenerateReportRequest] = Body(default=None),
    request: Request = None,
    current_user: Dict[str, Any] = Depends(require_roles(["doctor", "admin"]))
):
    """
    Generate a complete, professional, downloadable PDF report for a patient
    after an MRI/EEG analysis or upon clinical request.
    Restricted to Doctor and Admin roles.
    """
    req_dict = payload.model_dump() if (payload and hasattr(payload, "model_dump")) else (payload.dict() if payload else {})
    report_dict = patient_report_service.generate_report_for_patient(
        patient_id=patient_id,
        request_data=req_dict,
        current_user=current_user,
        request=request
    )
    return report_dict


# -----------------------------------------------------------------------------
# 2. VIEW REPORT DETAILS
# -----------------------------------------------------------------------------
@router.get(
    "/{report_id}",
    response_model=ReportDetailResponse,
    summary="View Report Details"
)
def get_report_details_endpoint(
    report_id: str,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """
    View report metadata and clinical diagnostic details.
    Patients may only view their own reports. Doctors & Admins have full access.
    """
    return patient_report_service.get_report_by_id(report_id, current_user)


# -----------------------------------------------------------------------------
# 3. DOWNLOAD REPORT PDF
# -----------------------------------------------------------------------------
@router.get(
    "/{report_id}/download",
    summary="Download Report PDF"
)
def download_report_pdf_endpoint(
    report_id: str,
    request: Request = None,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """
    Download the verified ReportLab PDF document for a specific report.
    Enforces doctor-patient ownership before streaming.
    """
    return patient_report_service.download_report_pdf(report_id, current_user, request=request)


# -----------------------------------------------------------------------------
# 4. PATIENT REPORT HISTORY
# -----------------------------------------------------------------------------
@router.get(
    "/patient/{patient_id}",
    response_model=List[ReportResponse],
    summary="Patient Report History"
)
def get_patient_report_history_endpoint(
    patient_id: str,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    """
    Retrieve all historical reports for a specific patient.
    Patients can only view their own reports.
    """
    return patient_report_service.get_patient_reports(patient_id, current_user)


# -----------------------------------------------------------------------------
# 5. DOCTOR'S ASSIGNED PATIENTS REPORTS
# -----------------------------------------------------------------------------
@router.get(
    "/doctor/{doctor_id}",
    response_model=List[ReportResponse],
    summary="Doctor's Patient Reports"
)
def get_doctor_patient_reports_endpoint(
    doctor_id: str,
    current_user: Dict[str, Any] = Depends(require_roles(["doctor", "admin"]))
):
    """
    Retrieve all reports generated by or assigned to a specific doctor.
    Restricted to Doctor and Admin roles.
    """
    return patient_report_service.get_doctor_reports(doctor_id, current_user)


# -----------------------------------------------------------------------------
# 6. AUTHORIZED REPORT DELETION
# -----------------------------------------------------------------------------
@router.delete(
    "/{report_id}",
    summary="Authorized Report Deletion"
)
def delete_report_endpoint(
    report_id: str,
    request: Request = None,
    current_user: Dict[str, Any] = Depends(require_roles(["doctor", "admin"]))
):
    """
    Soft-delete a report record.
    Patients: Forbidden (403).
    Doctors: Limited to deleting reports they generated.
    Admins: Unrestricted deletion.
    """
    return patient_report_service.delete_report(report_id, current_user, request=request)
